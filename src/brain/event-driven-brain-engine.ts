import type { EventBus } from "../core/event-bus";
import type { AssistantInput, AssistantResponse, ConversationMessage } from "../core/messages";
import { logger } from "../core/logger";
import { ConversationContext } from "./conversation-context";
import type { BrainEngine } from "./brain-engine";
import type { LanguageModel } from "./language-model";
import { FallbackRuleProvider } from "./fallback-rule-provider";

export class EventDrivenBrainEngine implements BrainEngine {
  private readonly unsubscribers: Array<() => void> = [];
  private readonly context = new ConversationContext();
  private statusTimer: ReturnType<typeof setInterval> | undefined;
  private queue: Promise<void> = Promise.resolve();
  private runId = 0;
  private running = false;

  constructor(
    private readonly events: EventBus,
    private readonly model: LanguageModel,
    private readonly fallback: LanguageModel = new FallbackRuleProvider(),
  ) {}

  start(): void {
    if (this.unsubscribers.length > 0) {
      return;
    }
    this.running = true;
    this.runId += 1;
    this.queue = Promise.resolve();
    this.unsubscribers.push(
      this.events.on("vision.sign-recognized", ({ recognition }) => {
        this.enqueue({
          type: "sign",
          timestamp: recognition.timestamp,
          recognition,
        });
      }),
      this.events.on("voice.transcription", ({ text, timestamp }) => {
        this.enqueue({ type: "transcription", text, timestamp });
      }),
    );
    void this.refreshModelStatus();
    this.statusTimer = setInterval(() => void this.refreshModelStatus(), 30_000);
    logger.info("brain", "Event-driven brain started");
  }

  stop(): void {
    this.running = false;
    this.runId += 1;
    this.queue = Promise.resolve();
    this.unsubscribers.splice(0).forEach((unsubscribe) => unsubscribe());
    if (this.statusTimer) {
      clearInterval(this.statusTimer);
    }
    this.statusTimer = undefined;
    this.context.clear();
    logger.info("brain", "Event-driven brain stopped");
  }

  getConversation(): readonly ConversationMessage[] {
    return this.context.getMessages();
  }

  private enqueue(input: AssistantInput): void {
    const runId = this.runId;
    this.queue = this.queue
      .then(() => {
        if (!this.isCurrentRun(runId)) {
          return;
        }
        return this.respond(input, runId);
      })
      .catch((error: unknown) => {
        // Keep the queue usable even if event listeners throw outside the
        // provider error handling in respond().
        logger.error("brain", "Unexpected conversation turn failure", error);
      });
  }

  private async respond(input: AssistantInput, runId: number): Promise<void> {
    if (!this.isCurrentRun(runId)) {
      return;
    }
    this.events.emit({ type: "conversation.state", state: "processing", message: "Processando sua fala..." });
    this.context.add({
      id: `user-${input.timestamp}`,
      role: "user",
      text: input.type === "sign" ? input.recognition.gloss : input.text,
      timestamp: input.timestamp,
    });
    // Use one snapshot for both providers so a fallback can never see a
    // different history than the primary provider did.
    const history = this.context.getMessages();

    try {
      let generated: Awaited<ReturnType<LanguageModel["generateResponse"]>>;
      try {
        generated = await this.model.generateResponse(input, history);
      } catch (primaryError) {
        if (!this.isCurrentRun(runId)) {
          return;
        }
        const details = primaryError instanceof Error ? primaryError.message : String(primaryError);
        logger.warn("brain", `Provider local indisponível; usando fallback por regras: ${details}`);
        generated = await this.fallback.generateResponse(input, history);
      }
      if (!this.isCurrentRun(runId)) {
        return;
      }
      const response: AssistantResponse = { ...generated, inReplyTo: input };
      this.context.add({
        id: `assistant-${input.timestamp}`,
        role: "assistant",
        text: response.text,
        source: response.source,
        timestamp: Date.now(),
      });
      this.events.emit({ type: "brain.response", response });
      logger.info("brain", `Response generated by ${response.source}`);
    } catch (error) {
      if (!this.isCurrentRun(runId)) {
        return;
      }
      const message =
        error instanceof Error ? error.message : "Falha ao gerar resposta no Brain.";
      this.events.emit({
        type: "core.error",
        source: "brain",
        message: `LLM_STATUS = UNAVAILABLE. ${message}`,
      });
      void this.refreshModelStatus();
      logger.error("brain", "Language model failed", error);
    }
  }

  private isCurrentRun(runId: number): boolean {
    return this.running && runId === this.runId;
  }

  private async refreshModelStatus(): Promise<void> {
    if (!this.model.checkAvailability) {
      return;
    }
    const runId = this.runId;
    if (!this.isCurrentRun(runId)) {
      return;
    }
    const model = this.model.modelName ?? "modelo local";
    this.events.emit({
      type: "brain.llm-status",
      status: "checking",
      model,
      message: `Verificando Ollama e modelo ${model}...`,
    });
    let availability;
    try {
      availability = await this.model.checkAvailability();
    } catch (error) {
      availability = {
        status: "unavailable" as const,
        model,
        message: error instanceof Error ? error.message : "Falha ao consultar o Ollama.",
      };
    }
    if (!this.isCurrentRun(runId)) {
      return;
    }
    this.events.emit({ type: "brain.llm-status", ...availability });
  }
}
